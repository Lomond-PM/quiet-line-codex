  const original = render([charcoal]);
  const erase = { ...line, tool: 'eraser', pressure: 1, width: 8 };
  const knead = { ...erase, tool: 'kneaded' };
  const erased = render([erase], { state: original.paintState }), kneaded = render([knead], { state: original.paintState });
