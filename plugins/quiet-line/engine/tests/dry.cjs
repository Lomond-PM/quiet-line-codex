  const controlled = { ...line, controls: [{ pressure: 0, width: .5, opacity: .2, angle: 170, tilt: 0 }, { pressure: 1, width: 2, opacity: 1, angle: -170, tilt: 1 }] };
  assert.notDeepEqual(render([controlled]).png, first.png);
