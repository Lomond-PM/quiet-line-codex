  assert.deepEqual(render([wrappedAngle]).png, render([{ ...wrappedAngle, controls: [{ angle: 0 }, { angle: 0 }] }]).png, 'full ±360 endpoints interpolate by the shortest path, not a full turn');
  const layers = render(Array.from({ length: 40 }, () => line)).paintState;
  assert.ok(mass(layers) > mass(first.paintState));
