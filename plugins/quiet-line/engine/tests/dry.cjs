'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const zlib = require('node:zlib');
const sharp = require('sharp');
const { renderDry } = require('../lib/dry-media.cjs');
const { saveDryState, loadDryState, cloneDryState, validateDryState, MAX_BYTES } = require('../lib/dry-state.cjs');
const style = { seed: 623, surface: 'warm', weight: 4, wobble: 0, pressure: 0, texture: .6, brush: 'pencil' };
const opts = { width: 128, height: 96, captureState: true };
const line = { tool: 'pencil', points: [[.2, .5], [.8, .5]], width: 5, pressure: .6 };
const render = (ops, extra = {}, st = {}) => renderDry(ops, { ...style, ...st }, { ...opts, ...extra });
const mass = s => s.bound.reduce((a, x, i) => a + x + s.loose[i], 0);
const centroid = s => {
  let amount = 0, xsum = 0;
  for (let i = 0; i < s.bound.length; i++) { const m = s.bound[i] + s.loose[i]; amount += m; xsum += (i % s.metadata.width) * m; }
  return xsum / amount;
};
const count = s => s.bound.reduce((a, x, i) => a + (x + s.loose[i] > .0001 ? 1 : 0), 0);
function stateHeader(s) {
  const copy = { ...s, metadata: { ...s.metadata, settings: { ...s.metadata.settings } } };
  for (const k of ['substrate', 'tooth', 'bound', 'loose', 'pigment']) copy[k] = { type: k === 'bound' || k === 'loose' ? 'f32' : 'u8', length: s[k].length };
  return copy;
}
function malformedFile(dir, header, payload = Buffer.from([0])) {
  const json = Buffer.from(JSON.stringify(header)), prefix = Buffer.alloc(12);
  prefix.write('QLDRY001'); prefix.writeUInt32LE(json.length, 8);
  const target = path.join(dir, 'malformed.qldry'); fs.writeFileSync(target, Buffer.concat([prefix, json, zlib.deflateSync(payload)])); return target;
}
